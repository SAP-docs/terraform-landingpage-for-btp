// Generates the Statistics docs category from stats.config.mjs:
//   docs/landing-page-content/statistics/
//     _category_.json      category metadata
//     index.mdx            generic intro + overview table
//     <key>.mdx            one detail page per provider / tool / module
//
// Re-run after editing stats.config.mjs (adding a provider/tool/module):
//   npm run gen-stats-pages
// The generated .mdx files are committed so the site builds without this step.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROVIDERS, TOOLS, MODULES } from '../stats.config.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'content', 'docs', 'landing-page-content', 'statistics');

const HEADER = `<!--\nGenerated by scripts/gen-stats-pages.mjs from stats.config.mjs — do not edit by hand.\nRun \`npm run gen-stats-pages\` to regenerate after changing the config.\n-->`;

function entityPage(kind, key, label, position) {
  return `---
sidebar_label: ${JSON.stringify(label)}
sidebar_position: ${position}
---

${HEADER}

import StatsEntity from '@site/src/components/stats/StatsEntity';

# ${label}

<StatsEntity kind="${kind}" entityKey="${key}" />
`;
}

const indexPage = `---
sidebar_label: Overview
sidebar_position: 0
tags:
  - Statistics
  - Downloads
  - Usage
---

${HEADER}

import StatsDashboard from '@site/src/components/stats/StatsDashboard';

# Statistics

Download and usage statistics for the Terraform/OpenTofu offering around SAP BTP:
the providers on the Terraform Registry, the SAP BTP Exporter, and published modules.

Numbers are refreshed daily from the [Terraform Registry](https://registry.terraform.io)
and GitHub releases. Pick an entry below for its detailed, interactive charts — the
version and release breakdowns let you choose how many entries to show.

<StatsDashboard />
`;

const category = {
  label: 'Statistics',
  collapsible: true,
  collapsed: true,
  position: 10,
  link: { type: 'doc', id: 'landing-page-content/statistics/index' },
};

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, '_category_.json'), JSON.stringify(category, null, 2) + '\n');
fs.writeFileSync(path.join(OUT, 'index.mdx'), indexPage);

let pos = 1;
for (const p of PROVIDERS) fs.writeFileSync(path.join(OUT, `${p.key}.mdx`), entityPage('provider', p.key, p.label, pos++));
for (const t of TOOLS) fs.writeFileSync(path.join(OUT, `${t.key}.mdx`), entityPage('tool', t.key, t.label, pos++));
for (const m of MODULES) fs.writeFileSync(path.join(OUT, `${m.key}.mdx`), entityPage('module', m.key, m.label, pos++));

console.log(`Generated ${1 + PROVIDERS.length + TOOLS.length + MODULES.length} pages in ${path.relative(ROOT, OUT)}`);
